#!/usr/bin/env python3
"""Write the Supabase migration files from the schema in ftz/db.py (the single source of truth).

    python3 tools/make_pg_migration.py

Produces supabase/migrations/*_ftz_schema.sql (tables, triggers) and *_ftz_security.sql (row level security, locked-down roles).
Apply them with the Supabase CLI (`supabase db push`), the SQL editor, or let an assistant run them through the Supabase MCP.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from ftz import db, pgcompat                                      # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "supabase", "migrations")
STAMP = "20261028000000"


def main():
    os.makedirs(OUT, exist_ok=True)
    schema = ("-- Globlexus FTZ Control: tables, safeguards. Generated by tools/make_pg_migration.py from ftz/db.py; do not edit by hand.\n"
              "CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA extensions;\n"
              "SET search_path = public, extensions;\n" + pgcompat.schema_sql(db.SCHEMA, db.NEW_COLUMNS) + "\n")
    security = ("-- Closes Supabase's public REST API for these tables and creates the least-privilege role the app connects as.\n"
                "-- After applying: ALTER ROLE ftz_app PASSWORD '<a long random password>';  (run it yourself; never commit it)\n" + pgcompat.SECURITY_SQL)
    for name, text in (("ftz_schema", schema), ("ftz_security", security)):
        path = os.path.join(OUT, f"{STAMP}_{name}.sql" if name == "ftz_schema" else f"{int(STAMP) + 1}_{name}.sql")
        with open(path, "w") as fh:
            fh.write(text)
        print("wrote", os.path.relpath(path))


if __name__ == "__main__":
    main()
